using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using ClothingAPI.Services.Implementations;

if (args.Length != 3) throw new ArgumentException("Usage: OptimizeAssets <source-images> <output-optimized> <typescript-manifest>");
var source = Path.GetFullPath(args[0]); var output = Path.GetFullPath(args[1]); var manifestPath = Path.GetFullPath(args[2]);
var manifest = new SortedDictionary<string, string>(StringComparer.Ordinal);
var rows = new List<object>();
var files = Directory.EnumerateFiles(source, "*", SearchOption.AllDirectories)
    .Where(x => !Path.GetRelativePath(source, x).StartsWith("optimized" + Path.DirectorySeparatorChar)
        && new[] { ".jpg", ".jpeg", ".png", ".webp" }.Contains(Path.GetExtension(x).ToLowerInvariant())).ToArray();
foreach (var file in files)
{
    var content = File.ReadAllBytes(file);
    var hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(ImageVariantEncoder.Version).Concat(content).ToArray()))[..16].ToLowerInvariant();
    var complete = true; var thumbSize = 0;
    foreach (var width in ImageVariantEncoder.Widths)
    {
        var bytes = ImageVariantEncoder.Encode(file, width);
        if (bytes is null) { complete = false; break; }
        var directory = Path.Combine(output, width.ToString()); Directory.CreateDirectory(directory);
        File.WriteAllBytes(Path.Combine(directory, hash + ".webp"), bytes);
        if (width == 640) thumbSize = bytes.Length;
    }
    if (!complete) continue;
    var relative = "assets/images/" + Path.GetRelativePath(source, file).Replace('\\', '/');
    manifest[relative] = hash;
    rows.Add(new { file = relative, originalBytes = content.Length, width640Bytes = thumbSize });
}
Directory.CreateDirectory(Path.GetDirectoryName(manifestPath)!);
File.WriteAllText(manifestPath, "// Generated by tests/tools/OptimizeAssets. Keep source originals.\nexport const OPTIMIZED_IMAGE_HASHES: Record<string, string> = "
    + JsonSerializer.Serialize(manifest, new JsonSerializerOptions { WriteIndented = true }) + ";\n");
Console.WriteLine(JsonSerializer.Serialize(new { images = manifest.Count, widths = ImageVariantEncoder.Widths, samples = rows.Take(8) }));
File.WriteAllText(Path.Combine(output, "sizes.json"), JsonSerializer.Serialize(rows, new JsonSerializerOptions { WriteIndented = true }));
